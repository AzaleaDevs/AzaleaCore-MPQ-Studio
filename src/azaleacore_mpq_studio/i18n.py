def normalize_language(language: object) -> str:
    """Devuelve un idioma soportado; usa español ante valores desconocidos."""
    return language if language in SUPPORTED_LANGUAGES else "es"


def translate_text(text: str, language: str) -> str:
    """Traduce los fragmentos de interfaz conocidos conservando rutas y datos."""
    language = normalize_language(language)
    pairs = (
        SPANISH_TO_ENGLISH.items()
        if language == "en"
        else ((english, spanish) for spanish, english in SPANISH_TO_ENGLISH.items())
    )
    for source, target in sorted(pairs, key=lambda pair: len(pair[0]), reverse=True):
        pattern = re.escape(source)
        if source and (source[0].isalnum() or source[0] == "_"):
            pattern = rf"(?<!\w){pattern}"
        if source and (source[-1].isalnum() or source[-1] == "_"):
            pattern = rf"{pattern}(?!\w)"
        text = re.sub(pattern, lambda _match: target, text)
    return text
